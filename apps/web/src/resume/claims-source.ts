import {
  parseResumeTex,
  type ResumeEntry,
  type ResumeLink,
  type ResumeTex,
} from "./resume-tex.ts";

export class ClaimsError extends Error {}

export type Claims = {
  name: string;
  headline: string;
  email: string;
  links: Record<"linkedin" | "github" | "website", ResumeLink>;
  education: ResumeEntry[];
  experience: ResumeEntry[];
  jobLinks: Record<string, string>;
};

function linkKind(url: string): keyof Claims["links"] {
  const host = new URL(url).hostname.replace(/^www\./, "");
  if (host === "linkedin.com") {
    return "linkedin";
  }
  if (host === "github.com") {
    return "github";
  }
  return "website";
}

function sectionEntries(tex: ResumeTex, title: string): ResumeEntry[] {
  const section = tex.sections.find((candidate) => candidate.title === title);
  if (!section) {
    throw new ClaimsError(`The resume has no "${title}" section with entries`);
  }
  return section.entries;
}

export function claimsFrom(tex: ResumeTex): Claims {
  const known = ["Education", "Work Experience"];
  const unknown = tex.sections.filter(({ title }) => !known.includes(title));
  if (unknown.length > 0) {
    throw new ClaimsError(
      `The resume has entries under sections the site does not show: ${unknown.map(({ title }) => title).join(", ")}`,
    );
  }

  const [email, ...otherEmails] = tex.emails;
  if (!email || otherEmails.length > 0) {
    throw new ClaimsError(
      `The resume must show exactly one email address, not ${tex.emails.length}`,
    );
  }

  const links: Partial<Claims["links"]> = {};
  for (const link of tex.links) {
    const kind = linkKind(link.url);
    if (links[kind]) {
      throw new ClaimsError(`The resume links more than one ${kind} address`);
    }
    links[kind] = link;
  }
  const { linkedin, github, website } = links;
  if (!linkedin || !github || !website) {
    throw new ClaimsError(
      "The resume's header must link LinkedIn, GitHub and one website",
    );
  }

  const experience = sectionEntries(tex, "Work Experience");
  const jobLinks: Record<string, string> = {};
  for (const { title, organisation, urls } of tex.jobLinks) {
    const [url] = urls;
    const isJob = experience.some(
      (entry) => entry.title === title && entry.organisation === organisation,
    );
    if (url && isJob) {
      jobLinks[organisation] = url;
    }
  }

  return {
    name: tex.name,
    headline: tex.headline,
    email,
    links: { linkedin, github, website },
    education: sectionEntries(tex, "Education"),
    experience,
    jobLinks,
  };
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function emit(value: unknown, indent: string): string {
  const inner = `${indent}  `;
  if (typeof value === "string") {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    if (value.length === 0) {
      return "[]";
    }
    return `[\n${value.map((item) => `${inner}${emit(item, inner)},\n`).join("")}${indent}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) {
      return "{}";
    }
    return `{\n${entries.map(([name, item]) => `${inner}${key(name)}: ${emit(item, inner)},\n`).join("")}${indent}}`;
  }
  throw new ClaimsError(`Cannot write ${String(value)} into claims.ts`);
}

export const claimsHeader =
  "// Generated by `pnpm claims` from resume/Irfan_Tayyab_SWE.tex. Edit the resume, not this file.";

export function claimsSource(tex: string): string {
  const claims = claimsFrom(parseResumeTex(tex));
  return `${claimsHeader}
import type { ResumeEntry, ResumeLink } from "./resume-tex";

export const resume = ${emit(claims, "")} as const satisfies {
  name: string;
  headline: string;
  email: string;
  links: Readonly<Record<"linkedin" | "github" | "website", ResumeLink>>;
  education: readonly ResumeEntry[];
  experience: readonly ResumeEntry[];
  jobLinks: Readonly<Record<string, string>>;
};
`;
}
